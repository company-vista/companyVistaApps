export function getCountryData(code) {
  const key = String(code || '').toUpperCase();
  return COUNTRIES.find(c => c.code === key) || null;
}

export function getCountryEntities(code) {
  const c = typeof code === 'object' && code !== null ? code : getCountryData(code);
  return Array.isArray(c?.entities) ? c.entities : [];
}

// UI display price: fixed countries show "$<fee>", quoted countries show ''.
export function getCountryPriceLabel(country) {
  const c = typeof country === 'string' ? getCountryData(country) : country;
  if (!c || c.pricingModel !== 'fixed' || !c.packageFee) return '';
  return `$${c.packageFee}`;
}

export function getCountryPrice(country) {
  const c = typeof country === 'string' ? getCountryData(country) : country;
  if (!c || c.pricingModel !== 'fixed' || !c.packageFee) return 0;
  return Number(c.packageFee);
}
